/**
 * Post-quantum key detection.
 *
 * Proton accounts that opted into post-quantum protection carry TWO primary
 * user keys, a v4 and a v6, and every address gains a v6 sibling.
 *
 * We now vendor Proton's OpenPGP.js fork, so the two algorithms Proton issues,
 * 30 (ML-DSA + Ed25519) and 35 (ML-KEM + X25519), parse and unlock normally.
 * The module still has to classify, because RFC 9980 defines five more ids that
 * no implementation ships: 31 and 36, and 32 to 34 (SLH-DSA). A key using one
 * of those fails while the ring is PARSED, before any passphrase is tried,
 * which is why find(Primary === 1) on the API's ordering fails at random.
 *
 * These tests build key packets byte by byte rather than using fixtures,
 * because the point is the packet header arithmetic: getting the length-field
 * width wrong shifts the algorithm byte and silently misclassifies every key.
 * tests/openpgp-pqc-pin.test.js checks the same parser against a REAL key
 * generated by the bundle, which is the independent oracle these cannot be.
 */

import { describe, it, expect } from 'vitest';
import { readFileSync } from 'fs';
import { join } from 'path';

const src = readFileSync(join(__dirname, '..', 'lib', 'pqc-detect.js'), 'utf-8');
// The module needs atob, which Node has as a global from 16 on.
const ProtonPqc = new Function('atob', src + '; return ProtonPqc;')(globalThis.atob);

/** Build an armored key block whose first packet has the given version/algo. */
function makeKey({ version = 4, algorithm = 27, newFormat = true, tag = 5, bodyLen = 60 } = {}) {
  const body = new Uint8Array(bodyLen);
  body[0] = version;
  // bytes 1..4 are the creation time, left as zero
  body[5] = algorithm;
  for (let i = 6; i < bodyLen; i++) body[i] = i & 0xff;

  let header;
  if (newFormat) {
    if (bodyLen < 192) header = [0xc0 | tag, bodyLen];
    else if (bodyLen < 8384) {
      const v = bodyLen - 192;
      header = [0xc0 | tag, 192 + (v >> 8), v & 0xff];
    } else {
      header = [0xc0 | tag, 255, (bodyLen >> 24) & 0xff, (bodyLen >> 16) & 0xff,
        (bodyLen >> 8) & 0xff, bodyLen & 0xff];
    }
  } else {
    // Old format: length-type 0 is one byte, 1 is two, 2 is four.
    if (bodyLen < 256) header = [0x80 | (tag << 2) | 0, bodyLen];
    else header = [0x80 | (tag << 2) | 1, (bodyLen >> 8) & 0xff, bodyLen & 0xff];
  }

  const packet = new Uint8Array(header.length + body.length);
  packet.set(header, 0);
  packet.set(body, header.length);
  let bin = '';
  for (const b of packet) bin += String.fromCharCode(b);
  const b64 = Buffer.from(bin, 'binary').toString('base64').replace(/(.{64})/g, '$1\n');
  return '-----BEGIN PGP PRIVATE KEY BLOCK-----\n' +
    'Version: ProtonMail\n' +
    '\n' + b64 + '\n=abcd\n' +
    '-----END PGP PRIVATE KEY BLOCK-----\n';
}

const V4_ED25519 = makeKey({ version: 4, algorithm: 27 });
// The two Proton actually issues, and that the vendored fork implements.
const V6_MLDSA = makeKey({ version: 6, algorithm: 30 });     // RFC 9980 lower bound
const V6_MLKEM = makeKey({ version: 6, algorithm: 35 });
// Defined by the RFC, implemented by nobody. These are what the module is
// still for, and what the "unreadable key" fixtures below are built from.
const V6_SLHDSA = makeKey({ version: 6, algorithm: 33 });    // SLH-DSA
const V6_MLKEM_1024 = makeKey({ version: 6, algorithm: 36 }); // upper bound

describe('reading the key header without OpenPGP.js', () => {
  it('reads a v4 ed25519 key', () => {
    expect(ProtonPqc.readKeyAlgorithm(V4_ED25519)).toEqual({ version: 4, algorithm: 27 });
  });

  it('reads a v6 post-quantum key', () => {
    expect(ProtonPqc.readKeyAlgorithm(V6_MLDSA)).toEqual({ version: 6, algorithm: 30 });
  });

  it('handles a two-byte new-format length', () => {
    const k = makeKey({ version: 6, algorithm: 35, bodyLen: 500 });
    expect(ProtonPqc.readKeyAlgorithm(k)).toEqual({ version: 6, algorithm: 35 });
  });

  it('handles a five-byte new-format length', () => {
    const k = makeKey({ version: 6, algorithm: 34, bodyLen: 9000 });
    expect(ProtonPqc.readKeyAlgorithm(k)).toEqual({ version: 6, algorithm: 34 });
  });

  it('handles old-format packet headers', () => {
    expect(ProtonPqc.readKeyAlgorithm(makeKey({ newFormat: false, algorithm: 22 })))
      .toEqual({ version: 4, algorithm: 22 });
    expect(ProtonPqc.readKeyAlgorithm(
      makeKey({ newFormat: false, version: 6, algorithm: 30, bodyLen: 400 })))
      .toEqual({ version: 6, algorithm: 30 });
  });

  it('handles a block with no armor headers at all', () => {
    const withHeaders = makeKey();
    const without = withHeaders.replace('Version: ProtonMail\n\n', '');
    expect(ProtonPqc.readKeyAlgorithm(without)).toEqual({ version: 4, algorithm: 27 });
  });

  it('returns null for junk rather than throwing', () => {
    expect(ProtonPqc.readKeyAlgorithm('not a key')).toBeNull();
    expect(ProtonPqc.readKeyAlgorithm('')).toBeNull();
    expect(ProtonPqc.readKeyAlgorithm(null)).toBeNull();
    expect(ProtonPqc.readKeyAlgorithm(undefined)).toBeNull();
  });

  it('returns null for an implausible version rather than guessing', () => {
    expect(ProtonPqc.readKeyAlgorithm(makeKey({ version: 99 }))).toBeNull();
  });
});

describe('classifying algorithms', () => {
  it('treats the whole RFC 9980 range as post-quantum', () => {
    for (let a = 30; a <= 36; a++) expect(ProtonPqc.isPqcAlgorithm(a)).toBe(true);
  });
  it('does not claim classical algorithms are post-quantum', () => {
    for (const a of [1, 18, 19, 22, 25, 27, 28]) expect(ProtonPqc.isPqcAlgorithm(a)).toBe(false);
  });
  it('accepts the two post-quantum algorithms the bundle implements', () => {
    // The assertion that inverted when the fork was vendored: these used to be
    // "unsupported" and are now ordinary keys.
    expect(ProtonPqc.isUnsupportedKey(V6_MLDSA)).toBe(false);
    expect(ProtonPqc.isUnsupportedKey(V6_MLKEM)).toBe(false);
    expect(ProtonPqc.isSupportedAlgorithm(30)).toBe(true);
    expect(ProtonPqc.isSupportedAlgorithm(35)).toBe(true);
  });
  it('still flags the post-quantum ids nobody implements', () => {
    expect(ProtonPqc.isUnsupportedKey(V6_SLHDSA)).toBe(true);
    expect(ProtonPqc.isUnsupportedKey(V6_MLKEM_1024)).toBe(true);
    // 31 to 34 sit BETWEEN the two supported ids, so a range check would wave
    // them through. This is why the module holds a set, not a bound.
    for (const algorithm of [31, 32, 33, 34, 36]) {
      expect(ProtonPqc.isSupportedAlgorithm(algorithm)).toBe(false);
    }
  });
  it('does not flag anything classical', () => {
    expect(ProtonPqc.isUnsupportedKey(V4_ED25519)).toBe(false);
    expect(ProtonPqc.isUnsupportedKey(makeKey({ algorithm: 28 }))).toBe(false);
  });
  it('errs towards usable when the header cannot be read', () => {
    // An unfamiliar but fine key must still be tried, not silently skipped.
    expect(ProtonPqc.isUnsupportedKey('garbage')).toBe(false);
  });
  it('leaves the gap at 29 classified exactly as before the swap', () => {
    // 29 is unassigned by IANA and no library implements it. The old rule was
    // "above 28 is unreadable", so it was already unsupported; the set must not
    // quietly widen the boundary while adding 30 and 35.
    expect(ProtonPqc.isSupportedAlgorithm(29)).toBe(false);
    expect(ProtonPqc.isSupportedAlgorithm(28)).toBe(true);
    expect(ProtonPqc.isPqcAlgorithm(29)).toBe(false);
  });
});

describe('a post-quantum account is now an ordinary account', () => {
  // Proton returns two primary keys, a v4 and a v6, and the order is not ours
  // to control. Both are readable now, so neither ordering is a special case.
  const v6First = [
    { ID: 'v6', Primary: 1, PrivateKey: V6_MLDSA },
    { ID: 'v4', Primary: 1, PrivateKey: V4_ED25519 },
  ];
  const v4First = [
    { ID: 'v4', Primary: 1, PrivateKey: V4_ED25519 },
    { ID: 'v6', Primary: 1, PrivateKey: V6_MLDSA },
  ];

  it('signs in with neither key skipped, whichever order the API returns', () => {
    for (const keys of [v6First, v4First]) {
      const sel = ProtonPqc.selectUsableKey(keys);
      expect(sel.allUnsupported).toBe(false);
      expect(sel.skippedUnsupported).toBe(false);
    }
  });

  it('takes the API\'s first primary, since both are usable', () => {
    expect(ProtonPqc.selectUsableKey(v6First).key.ID).toBe('v6');
    expect(ProtonPqc.selectUsableKey(v4First).key.ID).toBe('v4');
  });

  it('keeps both keys in the usable set, losing neither', () => {
    // Both go on to be unlocked, because an address-key Token may be wrapped
    // to either one.
    const { usable, unsupported } = ProtonPqc.classifyKeys(v6First);
    expect(usable.map(k => k.ID)).toEqual(['v6', 'v4']);
    expect(unsupported).toEqual([]);
  });

  it('still reports the account AS post-quantum', () => {
    // hasPqc means "this account opted in", not "and therefore it is broken".
    // Getting this backwards would silence the one diagnostic that can tell us
    // a real opted-in account signed in successfully.
    const sel = ProtonPqc.selectUsableKey(v6First);
    expect(sel.hasPqc).toBe(true);
    expect(sel.hasUnsupportedPqc).toBe(false);
  });
});

describe('choosing a user key when one cannot be read', () => {
  // SLH-DSA: defined by RFC 9980, implemented by no OpenPGP library.
  const v6First = [
    { ID: 'v6', Primary: 1, PrivateKey: V6_SLHDSA },
    { ID: 'v4', Primary: 1, PrivateKey: V4_ED25519 },
  ];
  const v4First = [
    { ID: 'v4', Primary: 1, PrivateKey: V4_ED25519 },
    { ID: 'v6', Primary: 1, PrivateKey: V6_SLHDSA },
  ];

  it('picks the readable key whichever order the API returns', () => {
    expect(ProtonPqc.selectUsableKey(v6First).key.ID).toBe('v4');
    expect(ProtonPqc.selectUsableKey(v4First).key.ID).toBe('v4');
  });

  it('reports that it skipped an unreadable key', () => {
    expect(ProtonPqc.selectUsableKey(v6First).skippedUnsupported).toBe(true);
    expect(ProtonPqc.selectUsableKey(v6First).hasPqc).toBe(true);
    expect(ProtonPqc.selectUsableKey(v6First).hasUnsupportedPqc).toBe(true);
  });

  it('is unchanged on an ordinary account', () => {
    const normal = [
      { ID: 'a', Primary: 1, PrivateKey: V4_ED25519 },
      { ID: 'b', Primary: 0, PrivateKey: V4_ED25519 },
    ];
    const sel = ProtonPqc.selectUsableKey(normal);
    expect(sel.key.ID).toBe('a');
    expect(sel.skippedUnsupported).toBe(false);
    expect(sel.hasPqc).toBe(false);
    expect(sel.allUnsupported).toBe(false);
  });

  it('prefers a primary key over a readable non-primary one', () => {
    const mixed = [
      { ID: 'sec', Primary: 0, PrivateKey: V4_ED25519 },
      { ID: 'pri', Primary: 1, PrivateKey: V4_ED25519 },
    ];
    expect(ProtonPqc.selectUsableKey(mixed).key.ID).toBe('pri');
  });

  it('falls back to a readable non-primary key rather than failing', () => {
    const onlyNonPrimaryReadable = [
      { ID: 'v6', Primary: 1, PrivateKey: V6_SLHDSA },
      { ID: 'old', Primary: 0, PrivateKey: V4_ED25519 },
    ];
    expect(ProtonPqc.selectUsableKey(onlyNonPrimaryReadable).key.ID).toBe('old');
  });

  it('signals allUnsupported when no key uses an algorithm we implement', () => {
    const allPqc = [
      { ID: 'v6a', Primary: 1, PrivateKey: V6_SLHDSA },
      { ID: 'v6b', Primary: 0, PrivateKey: V6_MLKEM_1024 },
    ];
    const sel = ProtonPqc.selectUsableKey(allPqc);
    expect(sel.allUnsupported).toBe(true);
    expect(sel.hasPqc).toBe(true);
    // Still returns something, so a caller that ignores the flag degrades to
    // today's behaviour rather than dereferencing null.
    expect(sel.key).not.toBeNull();
  });

  it('survives an empty or missing key list', () => {
    expect(ProtonPqc.selectUsableKey([]).key).toBeNull();
    expect(ProtonPqc.selectUsableKey(undefined).key).toBeNull();
    expect(ProtonPqc.selectUsableKey([]).allUnsupported).toBe(false);
  });

  it('splits a mixed set without losing any key', () => {
    const { usable, unsupported } = ProtonPqc.classifyKeys(v6First);
    expect(usable.map(k => k.ID)).toEqual(['v4']);
    expect(unsupported.map(k => k.ID)).toEqual(['v6']);
  });

  it('classifies public keys too, not just private ones', () => {
    const pub = [{ ID: 'p', Primary: 1, PublicKey: V6_MLKEM_1024 }];
    expect(ProtonPqc.classifyKeys(pub).unsupported.map(k => k.ID)).toEqual(['p']);
  });
});


/**
 * Choosing which address key SIGNS outgoing mail.
 *
 * `addressKeyMap` picks the ONE key used to sign and encrypt outgoing mail for
 * an address. It used to keep whichever key decrypted first, which is right
 * only while Proton returns the primary first AND that key decrypts.
 *
 * Two things make that insufficient. An address can carry several active keys
 * after a rotation. And on a post-quantum account it carries a v4 and a v6 at
 * once, where the v6 is for decryption only: WebClients signs with
 * `withV6SupportForSigning: false` because v6 signatures break parsing for some
 * third-party OpenPGP libraries. Signing with the wrong one is invisible to us,
 * since we verify our own signatures perfectly well; it breaks for the
 * recipient.
 *
 * Decryption success is only known after the attempt, so the choice is made
 * incrementally: this is a reducer, and these tests drive it as the unlock loop
 * would.
 */
describe('choosing the address key that signs outgoing mail', () => {
  const { preferAddressKeyForSigning } = ProtonPqc;
  const v4 = (primary) => ({ primary, version: 4 });
  const v6 = (primary) => ({ primary, version: 6 });

  it('takes the first key when nothing is chosen yet', () => {
    expect(preferAddressKeyForSigning(null, v4(false))).toBe(true);
    expect(preferAddressKeyForSigning(null, v6(true))).toBe(true);
  });

  it('upgrades a non-primary choice to a primary one', () => {
    expect(preferAddressKeyForSigning(v4(false), v4(true))).toBe(true);
  });

  it('never downgrades a primary choice to a non-primary one', () => {
    expect(preferAddressKeyForSigning(v4(true), v4(false))).toBe(false);
  });

  it('keeps the FIRST primary when an equally ranked primary follows', () => {
    expect(preferAddressKeyForSigning(v4(true), v4(true))).toBe(false);
  });

  it('keeps the first non-primary when another non-primary follows', () => {
    expect(preferAddressKeyForSigning(v4(false), v4(false))).toBe(false);
  });

  it('prefers the v4 primary over the v6 primary, whichever arrives first', () => {
    // THE post-quantum case: both flagged Primary, both decrypt.
    expect(preferAddressKeyForSigning(v6(true), v4(true))).toBe(true);
    expect(preferAddressKeyForSigning(v4(true), v6(true))).toBe(false);
  });

  it('prefers a v4 over a v6 among non-primary keys too', () => {
    expect(preferAddressKeyForSigning(v6(false), v4(false))).toBe(true);
    expect(preferAddressKeyForSigning(v4(false), v6(false))).toBe(false);
  });

  it('still ranks primary above version', () => {
    // A v6 primary beats a non-primary v4: Proton's own statement about which
    // key to use outranks our preference, and a non-primary key may have been
    // rotated out. Does not arise while opt-in leaves the v4 key primary.
    expect(preferAddressKeyForSigning(v6(true), v4(false))).toBe(false);
    expect(preferAddressKeyForSigning(v4(false), v6(true))).toBe(true);
  });

  it('treats v5 like v6, not like v4', () => {
    // The concern is any signature version a third-party parser may reject,
    // not post-quantum specifically.
    expect(preferAddressKeyForSigning({ primary: true, version: 5 }, v4(true))).toBe(true);
  });

  /** Drive the reducer over a key list the way the unlock loop does. */
  function choose(keys) {
    let chosen = null;
    let chosenChoice = null;
    for (const k of keys) {
      if (!k.decrypts) continue;
      const candidate = { primary: !!k.primary, version: k.version || 4 };
      if (preferAddressKeyForSigning(chosenChoice, candidate)) {
        chosen = k.id;
        chosenChoice = candidate;
      }
    }
    return chosen;
  }

  it('picks the primary regardless of the order the API returns', () => {
    const a = { id: 'a', primary: false, decrypts: true };
    const p = { id: 'p', primary: true, decrypts: true };
    expect(choose([a, p])).toBe('p');
    expect(choose([p, a])).toBe('p');
  });

  it('picks the v4 primary on a post-quantum address, either order', () => {
    const v6key = { id: 'v6', primary: true, version: 6, decrypts: true };
    const v4key = { id: 'v4', primary: true, version: 4, decrypts: true };
    expect(choose([v6key, v4key])).toBe('v4');
    expect(choose([v4key, v6key])).toBe('v4');
  });

  it('falls back to a non-primary when the primary cannot be decrypted', () => {
    expect(choose([
      { id: 'unreadable', primary: true, decrypts: false },
      { id: 'v4', primary: false, decrypts: true },
    ])).toBe('v4');
  });

  it('uses the v6 key when it is the only one that decrypts', () => {
    // Better to sign with v6 than not to send at all.
    expect(choose([
      { id: 'v6', primary: true, version: 6, decrypts: true },
      { id: 'v4', primary: true, version: 4, decrypts: false },
    ])).toBe('v6');
  });

  it('returns nothing when no key decrypts, rather than a broken choice', () => {
    expect(choose([
      { id: 'v6', primary: true, decrypts: false },
      { id: 'x', primary: false, decrypts: false },
    ])).toBeNull();
  });

  it('is unchanged from the old first-wins rule when no key is flagged', () => {
    // Proton omitting Primary must not change today's behaviour.
    expect(choose([
      { id: 'first', primary: false, decrypts: true },
      { id: 'second', primary: false, decrypts: true },
    ])).toBe('first');
  });

  it('treats only the literal flag as primary, never a truthy string', () => {
    // accounts.js compares Primary === 1; a stray '1' must not win.
    expect(preferAddressKeyForSigning(v4(false), v4('1' === 1))).toBe(false);
  });
});
